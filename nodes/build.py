#!/usr/bin/env python3
"""Embed nodes/runner.py into onboard.sh and onboard.ps1 so each stays a single file to copy.
Run after editing runner.py:  python3 nodes/build.py   (--check exits 1 if they are stale)."""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
BEGIN = "# >>> runner.py (generated by nodes/build.py; do not edit here)"
END = "# <<< runner.py"


def main() -> int:
    source = (HERE / "runner.py").read_text().rstrip("\n")
    # Each script embeds the runner in a quoted here-doc; these lines would end it early.
    for bad in ("RUNNER_PY", "'@"):
        if any(line.startswith(bad) for line in source.splitlines()):
            raise SystemExit(f"runner.py has a line starting with {bad!r}; it would break the here-doc")
    stale = []
    for name in ("onboard.sh", "onboard.ps1"):
        path = HERE / name
        text = path.read_text()
        pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
        if not pattern.search(text):
            raise SystemExit(f"{name}: runner markers not found")
        new = pattern.sub(lambda _: f"{BEGIN}\n{source}\n{END}", text)
        if new != text:
            stale.append(name)
            if "--check" not in sys.argv:
                path.write_text(new)
    if "--check" in sys.argv and stale:
        print("stale: " + ", ".join(stale) + " (run python3 nodes/build.py)")
        return 1
    print("updated: " + (", ".join(stale) or "nothing"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
